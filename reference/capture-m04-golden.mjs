// Regenerates tests/sim/prototype-golden.ts from reference/prototype-m04-etch.html.
//
// It runs the prototype's OWN functions (the text between `const W=260` and the rendering
// section, evaluated unmodified) in Node, so the numbers are the prototype's behaviour, not a
// re-derivation. The ported TypeScript in src/ is checked against this file in
// tests/sim/m04-parity.test.ts.
//
// Usage (from repo root):  node reference/capture-m04-golden.mjs
//                          npx prettier --write tests/sim/prototype-golden.ts
import fs from 'node:fs';

const html = fs.readFileSync(new URL('./prototype-m04-etch.html', import.meta.url), 'utf8');
const start = html.indexOf('const W=260');
const end = html.indexOf('/* ---------- rendering ---------- */');
if (start < 0 || end < 0) throw new Error('prototype markers not found');

const factory = new Function(
  'document',
  `${html.slice(start, end)}\nreturn {P, litho, buildGrid, etchRates, arrival, measure, W, H};`,
);
const proto = factory({ getElementById: () => null });
const DEFAULTS = { ...proto.P };

const STATUS = { ok: 'ok', w: 'marginal', x: 'fail' };

// ---- litho: one row per (rpm, source, design, dose) -------------------------------------
const lithoInputs = [
  [3000, 'i', 800, 1], // clear window, no taper
  [3000, 'i', 400, 1], // tapered sidewall (ratio < 1.3)
  [3000, 'i', 365, 1], // ratio exactly 1: not "near resolution", taper 24 nm
  [3000, 'i', 300, 1], // near resolution
  [3000, 'i', 150, 1], // below resolution
  [3000, 'i', 800, 0.7], // underdose -> scum
  [3000, 'i', 800, 1.5], // overdose
  [3000, 'g', 500, 1], // g-line near resolution
  [3000, 'arf', 150, 1], // ArF, tapered
  [1500, 'krf', 300, 0.8], // thick resist, underdose
  [6000, 'i', 300, 0.65], // thin resist, near resolution + underdose
];
const litho = lithoInputs.map(([rpm, lam, design, dose]) => {
  Object.assign(proto.P, DEFAULTS, { rpm, lam, design, dose });
  const li = proto.litho();
  return {
    rpm,
    source: lam,
    designNm: design,
    dose,
    resistThicknessNm: li.rt,
    cdMinNm: li.cdMin,
    ratio: li.r,
    printedNm: li.printed,
    scumNm: li.scum,
    taperNm: li.taper,
    status: STATUS[li.status],
  };
});

// ---- etch: full recipe -> prototype metrics + arrival-time fingerprint -------------------
const etchRecipes = [
  ['A', { mode: 'wet', wet: 'boe6', wetT: 3.3, design: 800 }],
  ['B', { mode: 'dry', power: 200, press: 30, dryT: 4.6, design: 800 }],
  ['C', { mode: 'dry', power: 80, press: 180, dryT: 9, design: 400 }],
  ['D', { mode: 'wet', wet: 'hf49', wetT: 0.12, design: 800 }],
  ['E', { mode: 'wet', wet: 'boe10', wetT: 8, design: 1200 }],
  ['F', { mode: 'dry', power: 300, press: 20, dryT: 14, design: 800 }],
  ['G', { mode: 'dry', power: 150, press: 100, dryT: 6, design: 400, dose: 0.7 }],
  ['H', { mode: 'wet', wet: 'boe6', wetT: 3.3, design: 300 }],
  ['I', { mode: 'dry', power: 250, press: 60, dryT: 8, design: 600, rpm: 6000, lam: 'g' }],
  ['J', { mode: 'dry', power: 120, press: 40, dryT: 3, design: 1200 }],
];
const etch = etchRecipes.map(([id, over]) => {
  Object.assign(proto.P, DEFAULTS, over);
  const P = proto.P;
  const grid = proto.buildGrid('developed');
  const arr = proto.arrival(grid, proto.etchRates());
  const timeMin = P.mode === 'wet' ? P.wetT : P.dryT;
  const m = proto.measure(grid, arr, timeMin);
  let finiteCount = 0;
  let sumFinite = 0;
  for (const v of arr) {
    if (Number.isFinite(v)) {
      finiteCount++;
      sumFinite += v;
    }
  }
  const recipe =
    P.mode === 'wet'
      ? { mode: 'wet', etchant: P.wet, timeMin }
      : { mode: 'dry', powerW: P.power, pressureMTorr: P.press, timeMin };
  return {
    id,
    litho: { rpm: P.rpm, source: P.lam, designNm: P.design, dose: P.dose },
    recipe,
    metrics: {
      printedNm: m.printed,
      cleared: m.cleared,
      topNm: m.top,
      bottomNm: m.bot,
      undercutNm: m.under,
      siLossNm: m.siLoss,
      resistLeftNm: m.prLeft,
      sidewallAngleDeg: m.angle,
    },
    arrival: { finiteCount, sumFinite },
  };
});

const out = `// GENERATED by reference/capture-m04-golden.mjs from reference/prototype-m04-etch.html.
// Do not edit by hand; regenerate with the command in that script's header.
// Values are the prototype's own output, kept at full double precision.

export interface GoldenLitho {
  rpm: number;
  source: 'g' | 'i' | 'krf' | 'arf';
  designNm: number;
  dose: number;
  resistThicknessNm: number;
  cdMinNm: number;
  ratio: number;
  printedNm: number;
  scumNm: number;
  taperNm: number;
  status: 'ok' | 'marginal' | 'fail';
}

export type GoldenRecipe =
  | { mode: 'wet'; etchant: 'boe10' | 'boe6' | 'hf49'; timeMin: number }
  | { mode: 'dry'; powerW: number; pressureMTorr: number; timeMin: number };

export interface GoldenEtch {
  id: string;
  litho: { rpm: number; source: 'g' | 'i' | 'krf' | 'arf'; designNm: number; dose: number };
  recipe: GoldenRecipe;
  metrics: {
    printedNm: number;
    cleared: boolean;
    topNm: number;
    bottomNm: number;
    undercutNm: number;
    siLossNm: number;
    resistLeftNm: number;
    sidewallAngleDeg: number;
  };
  /** Fingerprint of the full arrival-time field: cells with finite arrival, and their sum (min). */
  arrival: { finiteCount: number; sumFinite: number };
}

export const GOLDEN_LITHO: readonly GoldenLitho[] = ${JSON.stringify(litho, null, 2)};

export const GOLDEN_ETCH: readonly GoldenEtch[] = ${JSON.stringify(etch, null, 2)};
`;
fs.mkdirSync(new URL('../tests/sim/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../tests/sim/prototype-golden.ts', import.meta.url), out);
console.log(`wrote tests/sim/prototype-golden.ts (${litho.length} litho rows, ${etch.length} etch cases)`);
